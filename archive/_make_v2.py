# ── Cell 8: training loop — add per-epoch checkpoint saving ──
cells[8]['source'] = [
    '# ── Training loop with early stopping + auto-save ──\n',
    'best_f1 = 0.0\n',
    'best_epoch = 0\n',
    'patience_counter = 0\n',
    'history = {"train_loss": [], "val_f1": [], "val_acc": []}\n',
    '\n',
    'print(f\'{"Epoch":>5} | {"Train Loss":>10} | {"Val F1":>8} | {"Val Acc":>8} | {"Status"}\')\n',
    'print("-" * 60)\n',
    '\n',
    'for epoch in range(1, MAX_EPOCHS + 1):\n',
    '    # ── Train ──\n',
    '    model.train()\n',
    '    running_loss = 0.0\n',
    '    num_batches = 0\n',
    '\n',
    '    pbar = tqdm(train_loader, desc=f"Epoch {epoch} [Train]", leave=False)\n',
    '    for batch in pbar:\n',
    '        batch = {k: v.to(device) for k, v in batch.items()}\n',
    '        labels = batch.pop("labels")\n',
    '\n',
    '        optimizer.zero_grad()\n',
    '        outputs = model(**batch, use_itm_head=True)\n',
    '        loss = criterion(outputs.itm_score, labels)\n',
    '        loss.backward()\n',
    '        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)\n',
    '        optimizer.step()\n',
    '        scheduler.step()\n',
    '\n',
    '        running_loss += loss.item()\n',
    '        num_batches += 1\n',
    '        pbar.set_postfix(loss=f"{loss.item():.4f}")\n',
    '\n',
    '    avg_loss = running_loss / num_batches\n',
    '    history["train_loss"].append(avg_loss)\n',
    '\n',
    '    # ── Validate ──\n',
    '    model.eval()\n',
    '    all_preds, all_labels = [], []\n',
    '\n',
    '    with torch.no_grad():\n',
    '        for batch in tqdm(val_loader, desc=f"Epoch {epoch} [Val]", leave=False):\n',
    '            batch = {k: v.to(device) for k, v in batch.items()}\n',
    '            labels = batch.pop("labels")\n',
    '\n',
    '            outputs = model(**batch, use_itm_head=True)\n',
    '            preds = outputs.itm_score.argmax(dim=1)\n',
    '\n',
    '            all_preds.extend(preds.cpu().numpy())\n',
    '            all_labels.extend(labels.cpu().numpy())\n',
    '\n',
    '    # ITM labels: 1=match(real), 0=no-match(fake)\n',
    '    # For F1 on fake detection: convert to our convention (fake=1)\n',
    '    y_true = [1 - l for l in all_labels]  # flip: ITM 1->0(real), ITM 0->1(fake)\n',
    '    y_pred = [1 - p for p in all_preds]\n',
    '\n',
    '    val_f1  = f1_score(y_true, y_pred)\n',
    '    val_acc = accuracy_score(y_true, y_pred)\n',
    '    history["val_f1"].append(val_f1)\n',
    '    history["val_acc"].append(val_acc)\n',
    '\n',
    '    # ── Per-epoch checkpoint ──\n',
    '    epoch_ckpt_dir = os.path.join(CHECKPOINT_DIR, f"epoch_{epoch}")\n',
    '    os.makedirs(epoch_ckpt_dir, exist_ok=True)\n',
    '    model.save_pretrained(epoch_ckpt_dir)\n',
    '    processor.save_pretrained(epoch_ckpt_dir)\n',
    '    with open(os.path.join(epoch_ckpt_dir, "training_history.json"), "w") as f:\n',
    '        json.dump(history, f, indent=2)\n',
    '\n',
    '    # ── Early stopping + best checkpoint ──\n',
    '    if val_f1 > best_f1:\n',
    '        best_f1 = val_f1\n',
    '        best_epoch = epoch\n',
    '        patience_counter = 0\n',
    '        model.save_pretrained(SAVE_DIR)\n',
    '        processor.save_pretrained(SAVE_DIR)\n',
    '        with open(os.path.join(SAVE_DIR, "training_history.json"), "w") as f:\n',
    '            json.dump(history, f, indent=2)\n',
    '        status = f"** BEST ** (saved to {SAVE_DIR})"\n',
    '    else:\n',
    '        patience_counter += 1\n',
    '        status = f"patience {patience_counter}/{PATIENCE}"\n',
    '\n',
    '    print(f"{epoch:>5} | {avg_loss:>10.4f} | {val_f1:>8.4f} | {val_acc:>8.4f} | {status}")\n',
    '\n',
    '    if patience_counter >= PATIENCE:\n',
    '        print(f"\\nEarly stopping at epoch {epoch}. Best epoch: {best_epoch} (F1: {best_f1:.4f})")\n',
    '        break\n',
    '\n',
    'print(f"\\nTraining complete. Best val F1: {best_f1:.4f} at epoch {best_epoch}")\n',
    'print(f"Best checkpoint saved at: {SAVE_DIR}")\n',
    'print(f"Per-epoch checkpoints at: {CHECKPOINT_DIR}")',
]
cells[8]['outputs'] = []
